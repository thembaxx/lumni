import { readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync, createWriteStream } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { ZipArchive } from "archiver";

const __dirname = dirname(fileURLToPath(import.meta.url));

const ANIMATIONS_DIR = resolve(__dirname, "..", "src", "assets", "animations");
const OUTPUT_DIR = resolve(__dirname, "..", "public", "animations");
const SOURCES_OUTPUT = resolve(
  __dirname,
  "..",
  "src",
  "components",
  "lottie",
  "animation-sources.ts",
);

const TITLE_MAP = {
  "achievement-unlock": "Achievement Unlock",
  "level-up": "Level Up",
  confetti: "Confetti",
  "success-check": "Success Check",
  "loading-dots": "Loading Dots",
  "loading-lumni": "Lumni Loading",
  "page-404": "Page Not Found",
  "quiz-correct": "Quiz Correct",
  "quiz-incorrect": "Quiz Incorrect",
  "streak-fire": "Streak Fire",
  "xp-burst": "XP Burst",
  "empty-search": "Empty Search",
  "empty-upload": "Empty Upload",
  "error-state": "Error State",
};

function toPascalCase(str) {
  return str
    .split("-")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

async function createLottieArchive(id, jsonPath, outputPath) {
  const jsonData = JSON.parse(readFileSync(jsonPath, "utf-8"));
  const w = jsonData.w ?? 200;
  const h = jsonData.h ?? 200;
  const fr = jsonData.fr ?? 60;

  const manifest = {
    version: 2,
    animations: [
      {
        id,
        title: TITLE_MAP[id] ?? toPascalCase(id),
        w,
        h,
        fr,
      },
    ],
  };

  return new Promise((resolve, reject) => {
    const output = createWriteStream(outputPath);
    const archive = new ZipArchive({ zlib: { level: 9 } });

    output.on("close", () => resolve(archive.pointer()));
    archive.on("error", reject);

    archive.pipe(output);
    archive.append(JSON.stringify(manifest, null, 2), {
      name: "manifest.json",
    });
    archive.append(JSON.stringify(jsonData), { name: `${id}.json` });
    archive.finalize();
  });
}

async function main() {
  if (!existsSync(OUTPUT_DIR)) {
    mkdirSync(OUTPUT_DIR, { recursive: true });
  }

  const files = readdirSync(ANIMATIONS_DIR).filter(
    (f) => f.endsWith(".json") && !f.endsWith(".lottie"),
  );

  const sources = {};
  let totalBytes = 0;

  for (const file of files) {
    const id = file.replace(/\.json$/, "");
    const jsonPath = resolve(ANIMATIONS_DIR, file);
    const outputPath = resolve(OUTPUT_DIR, `${id}.lottie`);

    const size = await createLottieArchive(id, jsonPath, outputPath);
    totalBytes += size;
    sources[id] = `/animations/${id}.lottie`;

    console.log(
      `  ✓ ${id}.lottie (${(size / 1024).toFixed(1)} KB)`,
    );
  }

  const sortedKeys = Object.keys(sources).sort();
  const sourceEntries = sortedKeys
    .map((key) => `  "${key}": "${sources[key]}",`)
    .join("\n");

  const tsContent = `// Auto-generated by scripts/generate-lottie-assets.mjs
// Do not edit manually — run \`bun run scripts/generate-lottie-assets.mjs\` to regenerate.

export const ANIMATION_SOURCES = {
${sourceEntries}
} as const;

export type AnimationSourceName = keyof typeof ANIMATION_SOURCES;
`;

  writeFileSync(SOURCES_OUTPUT, tsContent, "utf-8");

  console.log(`\nGenerated ${files.length} .lottie archives (${(totalBytes / 1024).toFixed(1)} KB total)`);
  console.log(`Sources map written to ${SOURCES_OUTPUT}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
